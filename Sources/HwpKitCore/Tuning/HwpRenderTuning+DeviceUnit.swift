import CoreGraphics

// MARK: - 장치 단위 무늬 — 대시·원형 점선 공용 (본체 파일 길이를 지키려 확장으로 둔다)

public extension HwpRenderTuning.LineShape {
    // 한글은 대시 무늬(긴 점선·점선·일점쇄선·이점쇄선·긴 파선)와 원형 점선을 글자 크기·두께에 비례하는
    // 연속값이 아니라 **600dpi 장치 단위(`deviceUnit`, 0.12pt)의 정수**로 그린다 — 요소 길이를 먼저
    // 정수로 정한 뒤 되풀이하므로 선 하나 안의 주기는 일정하고, 비례로 두면 주기마다 차가 쌓여 긴 선에서
    // 대시가 한글과 어긋난다 (1mm 점선 주기 86.61u vs 한글 87·88u — #245). 무늬는 **무늬 두께**
    // t(HWPUNIT 정수)에서 푼다: 글자선은 글자 크기(HWPUNIT) × 0.039를 반올림한 값
    // (`characterPatternThicknessPerMille`), 표 셀 테두리·단 구분선은 표 26 굵기마다 한글이 쓰는 값
    // (`borderPatternHwpUnits`)이다. 단위 b = t × 22/15 ÷ 12 (u, `patternUnitThicknessNumerator`/
    // `…Denominator`)이고, 점 q = round(b)는 원형 점선의 점 단위와 같다 (원의 규칙은
    // `HwpRenderTuning+Circle.swift`, 대시의 요소 식은 `HwpLineShapeGeometry+Dashes.swift`).
    // 반올림은 모두 0.5를 올린다.

    /// 한글이 대시·원형 점선을 그리는 장치 단위 (pt) — 600dpi 한 칸(72/600). 대시의 선·공백 길이와
    /// 원의 지름·간격, 테두리·단 구분선과 글자선(밑줄·취소선, #252)의 실선·대시 획 두께가 이 단위의
    /// 정수다.
    static let deviceUnit: CGFloat = 0.12

    /// 글자선 무늬 두께 (HWPUNIT) = 글자 크기(HWPUNIT) × 이 값 ÷ 1000을 반올림 (0.039em). 대시의 단위
    /// b는 이 두께 × 22/15(`patternUnitThicknessNumerator`/`…Denominator`)를 장치 단위로 잰 값(반올림
    /// 전 — 요소마다 배수를 곱한 뒤 반올림)이고, 원형 점선의 점 단위 q는 b를 반올림한 값이다 — 두께를
    /// 먼저 HWPUNIT으로 반올림해야 한글의 전환점이 설명된다. 원형
    /// 점선 실측(점 단위가 바뀌는 크기, HWPUNIT): 730→731(3→4u)·935→936(4→5)·1141→1142(5→6)·
    /// 1371→1372(6→7)·1576→1577(7→8)·2192→2193(10→11)·2423→2424(11→12)·4730→4732(22→23)·
    /// 6602→6604(31→32)·8704→8706(41→42) — 한 번 반올림한 비례식으로는 9.36pt(5u)와 47pt(22u)를
    /// 함께 설명할 수 없다. 대시 실측(#245): 한글 문서 취소선 대시 5종 × 무늬 두께 4~390 991표본·
    /// 아래 밑줄 90표본, MS 워드 호환 문서 취소선 580표본이 모두 이 두께의 식과 같다. 밑줄은 줄 글자
    /// 기본 크기, 취소선은 run의 글자 모양 기본 크기가 입력이다 (#226 — 상대 크기·위 첨자 전). MS 워드
    /// 호환 문서는 밑줄이 **줄 글자 상자의 높이**(글꼴 줄 상자, 함초롬바탕 1.69em·Times New Roman
    /// 1.15em — 문단 끝 글자·개체가 쌓이지 않은 줄에서는 한글 줄 캐시 `vertsize`와 같다), 취소선이
    /// 글자 모양 기본 크기다 (#244 — 글꼴 10종 × 8~100pt 밑줄 732표본·취소선 180표본). 같은 두께가
    /// 글자선의 실선·대시 획도 정한다 — max(1, round(t ÷ 12))u (#252, 한글 12.30 PDF: 한글 문서
    /// 1,275·MS 워드 호환 문서 972표본(build 6446)과 build 6523의 경계 쌍·글꼴 11종 810표본 전부,
    /// `HwpDecorationLineGeometry.strokeThickness(referenceSize:)`).
    static let characterPatternThicknessPerMille: CGFloat = 39

    /// 글자선 2중선·물결·2중 물결의 띠 (HWPUNIT) = 기준 크기(HWPUNIT) × 이 값 ÷ 1000을 반올림
    /// (0.113em, #252). 장치 띠 r = round(띠 ÷ 12)u에서 획 w = round(r ÷ 4)u를 내고, 2중선은 두께 w 두
    /// 줄이 중심 사이 3w, 물결은 대각선의 가로·세로가 r·반주기 r + 1·획 w, 2중 물결은 같은 물결을 3w
    /// 아래에 하나 더 긋는다. 띠 가운데는 글자 아래 밑줄이 줄 상자 바닥 + ⌊띠/2⌋, 글자 위 밑줄이 상자
    /// 상단 − ⌊띠/2⌋, 취소선이 단선 중심이다 (`HwpLineShapeGeometry+CharacterBands.swift`). 실측: 한글
    /// 12.30 build 6523 PDF (2026-10-03, `probes/252`) — 2중선·물결·2중 물결 × 아래 밑줄 1~100pt(1pt
    /// 간격)·취소선·위 밑줄 3~99pt 450표본과 계수·반올림 차례를 가르는 크기(4.53·6.15·7.92·…·64.2pt,
    /// 1~4pt 0.1pt 간격) 210표본, MS 워드 호환 문서 글꼴 4종 144표본(기준 크기는 줄 글자 상자 높이)이
    /// 모두 같다 — 0.112·0.12em, 반올림 한 번(round(X × 0.113 ÷ 12)), r을 거치지 않은 획(round(띠 ÷
    /// 48))은 어긋난다. 계수는 [0.113, 0.11301)까지 맞고 가장 단순한 113‰을 쓴다.
    static let characterDoubleBandPerMille: CGFloat = 113

    /// 글자선 가는+굵은 선·굵은+가는 선·3중선의 띠 (HWPUNIT) = 기준 크기(HWPUNIT) × 이 값 ÷ 1000을
    /// 반올림 (0.198em, #252). 장치 띠 E = round(띠 ÷ 12)u를 가는+굵은 선은 가는 선·공백 ⌊E/4⌋(최소
    /// 1u)·굵은 선 E − 2⌊E/4⌋(최소 3u, E ≤ 2u면 E 한 줄)로, 3중선은 가는 선·공백 max(1, ⌊E/6⌋)·굵은 선
    /// E − 4 × 그 값(E ≤ 5u면 min(E − 2, 2)u)으로 나눈다. 실측: 같은 문서 — 세 모양 × 아래 밑줄
    /// 1~100pt·취소선·위 밑줄 3~99pt 450표본, 1~4pt 0.1pt 간격·갈림 크기 237표본(앞 표본의 선이 측정
    /// 창에 섞인 3개는 그 선을 빼면 같다), MS 워드 호환 문서 144표본이 모두 같다 (0.2em이면 가는+굵은
    /// 선 300표본 중 78개만 맞는다). 계수는 [0.19796, 0.19801]까지 맞고 198‰을 쓴다.
    static let characterThickBandPerMille: CGFloat = 198

    /// 무늬 단위의 두께 배율 22/15의 분자 — 대시의 단위 b = 무늬 두께 × 22/15 (장치 단위, 요소마다
    /// 배수를 곱해 반올림)·원형 점선의 점 단위 q = round(b). 반올림 경계(0.5u)를 정확히 가르도록 정수
    /// 분수로 둔다 — 22/15를 이진 소수로
    /// 곱하면 두께 315HWPUNIT의 38.5u가 38.4999…로 내려가 80.65pt에서 원 간격 95u가 된다 (한글 실측
    /// 98u; 149.88pt(두께 585)도 한글 180u vs 178u — 두께 0~200만HWPUNIT 중 6,809곳이 이런 동점이다).
    static let patternUnitThicknessNumerator: CGFloat = 22

    /// 무늬 단위의 두께 배율 22/15의 분모 (`patternUnitThicknessNumerator`)
    static let patternUnitThicknessDenominator: CGFloat = 15

    /// 표 26 테두리선 굵기마다 한글이 무늬와 획을 재는 두께 (HWPUNIT, 0.1·0.12·0.15·0.2·0.25·0.3·0.4·
    /// 0.5·0.6·0.7·1·1.5·2·3·4·5mm 차례) — 표 셀 테두리와 단 구분선의 대시 단위·원형 점선 단위·획
    /// 두께가 이 값에서 나온다. 굵기를 HWPUNIT으로 반올림한 값(28·34·43·57·71·85·113·142·170·198·283·
    /// 425·567·850·1134·1417)과 여덟 굵기에서 1 작다: 한글 12.30 PDF의 긴 대시 길이가 0.12mm 40u·
    /// 0.15mm 51u·0.2mm 68u·0.5mm 172u·1.5mm 518u라 반올림한 두께의 22/15 × 10(41.6·52.6·69.7·
    /// 173.6·519.4u)로는 설명되지 않는다. 굵기에서 이 값을 내는 반올림 식(mm·pt·HWPUNIT·장치 단위의
    /// 곱과 내림·반올림·올림)은 찾지 못해 실측한 값을 표로 둔다 — 대시 5종 × 굵기 16단 × 셀 간격
    /// 0·283HWPUNIT의 가로·세로 변 317표본과 단 구분선 68표본의 선·공백 길이가 모두 이 두께의 식과
    /// 같다 (2026-10-01 `probes/245`). 획 두께(이 값 ÷ 12를 반올림한 장치 단위 — 2·3·4·5·6·7·9·12·
    /// 14·17·24·35·47·71·95·118u)와 원형 점선은 반올림한 두께로 셈해도 같은 값이다.
    static let borderPatternHwpUnits: [CGFloat] = [
        28, 33, 42, 56, 70, 84, 113, 141, 169, 198, 283, 424, 567, 850, 1134, 1417,
    ]

    /// 대시의 점(무늬 1)·짧은 선 하한 (장치 단위) — 무늬 두께가 4HWPUNIT(1pt 글자)이라 점 단위가 0이
    /// 되어도 한글은 1u 점을 그린다 (#245 실측).
    static let dashMinimumDotDeviceUnits: CGFloat = 1

    /// 대시의 긴 선(무늬 10) 하한 (장치 단위) — 무늬 두께 4~7HWPUNIT(1~1.9pt 글자)에서 긴 파선·
    /// 쇄선의 긴 선은 10u, 긴 점선의 선은 그 절반 5u다 (#245 실측: 반올림 값은 5·6·7·9u).
    static let dashMinimumLongDeviceUnits: CGFloat = 10

    /// 점 무늬 점선(1·1.5)의 공백 하한 (장치 단위) — 점 단위 1·2u(무늬 두께 20HWPUNIT, 약 5.2pt
    /// 글자 이하)에서도 공백은 4u다 (#245 실측: T 4~12 [1, 4]u, 13~20 [2, 4]u — 원형 점선의 간격
    /// 하한(점 몫 3u + 공백 2u)과 같은 주기다).
    static let dashMinimumDotGapDeviceUnits: CGFloat = 4

    /// 점 무늬 긴 점선·긴 파선·쇄선의 공백(무늬 3) 하한 (장치 단위) — 1pt 글자의 2u가 실측 최솟값이고
    /// 그보다 작은 무늬 두께에서 공백이 0이 되어 실선으로 붙지 않게 둔다.
    static let dashMinimumLongGapDeviceUnits: CGFloat = 2
}
