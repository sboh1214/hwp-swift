import Foundation

/// 문서 뷰가 배율을 뷰포트에 맞추는 방식 (#78).
///
/// **원샷 명령**이다 — 호스트가 `Binding<HwpZoomFit?>`에 값을 넣으면 뷰가 배율을
/// 한 번 적용하고 바인딩을 nil로 되돌린다. 지속 모드가 아니므로 창을 리사이즈해도
/// 다시 맞추지 않는다: 그 사이 사용자가 핀치로 바꾼 배율을 조용히 덮지 않으려는
/// 것이 이유이고, 다시 맞추려면 버튼을 다시 누른다.
///
/// 이 타입이 렌더 코어에 있는 이유는 뷰(HwpKitNative)·SwiftUI 표면(HwpKit)·호스트
/// 셋이 모두 의존하는 **가장 낮은 공통 모듈**이라서다. HwpKitNative에 두어도
/// 호스트가 이름 부를 수는 있지만(프로덕트로 선언돼 있다), 그러면 호스트가 링크
/// 하지 않는 것이 관례인 모듈의 타입이 공개 시그니처에 나타난다
/// (`Sample/project.yml`은 `HwpKit`·`HwpKitCore`만 링크한다).
/// `HwpPDFExportProgress`가 같은 자리에 있는 것도 같은 기준이다.
///
/// 두 가지가 근사치다. 배율은 네이티브 한계(`0.25...5.0`)로 클램프되므로 거대한
/// 쪽·좁은 창에서는 "맞춤"이 최선치이고, 로딩이 끝나기 전(`isComplete == false`)에
/// 맞추면 뒤에 오는 더 넓은 쪽이 캔버스를 넓혀 결과가 낡는다 — 원샷이라 스스로
/// 다시 맞추지 않으므로 그때는 다시 누른다.
public enum HwpZoomFit: Sendable, Hashable, CaseIterable {
    /// 스크롤 캔버스 **폭**을 뷰포트 폭에 맞춘다. 배율만 바꾸고 스크롤은 옮기지
    /// 않는다 (`currentPage`를 함께 바인딩했다면 그 왕복이 쪽 머리로 되돌릴 수는
    /// 있다 — 배율을 바꾸는 다른 경로와 같은 동작이다).
    case width
    /// 현재 쪽이 통째로 보이도록 폭·높이 중 더 빡빡한 축에 맞추고 그 쪽 위로 스크롤한다.
    case page
}
